"use strict";

// Utility script to (re)build lightweight JS bundles for the Language Mixer
// from the canonical JSON configs:
//   - config/language-mixes.json       -> config/language-mixes-all.js
//   - config/language-mixer-map.json   -> config/language-mixer-map.js
//
// Run from the project root with:
//   node tools/generate-language-mixer.js
//
// After you edit either JSON file to add more languages, rerun this script so
// the UI and local Markov mixer see the updated data.

const fs = require("fs");
const path = require("path");

const root = __dirname ? path.resolve(__dirname, "..", "..") : process.cwd();

function readJson(relativePath) {
  const full = path.join(root, relativePath);
  const raw = fs.readFileSync(full, "utf8");
  const clean = raw.replace(/^\uFEFF/, "");
  return JSON.parse(clean);
}

function writeFile(relativePath, contents) {
  const full = path.join(root, relativePath);
  fs.mkdirSync(path.dirname(full), {recursive: true});
  fs.writeFileSync(full, contents, "utf8");
  console.log("Wrote", relativePath.replace(/\\/g, "/"));
}

function buildLanguageMixesBundle() {
  const mixes = readJson("config/language-mixes.json");

  // Keep a stable sort order (region + name) for nicer UI grouping.
  mixes.sort((a, b) => {
    const ak = (a.region || "") + (a.name || "");
    const bk = (b.region || "") + (b.name || "");
    return ak.localeCompare(bk);
  });

  const banner = [
    '"use strict";',
    "",
    "// Auto-generated by tools/generate-language-mixer.js from config/language-mixes.json.",
    "// Edit the JSON source and rerun the generator if you change the catalog.",
    "(function(){",
    "  window.languageMixerCatalog = " + JSON.stringify(mixes, null, 2) + ";",
    "})();",
    ""
  ].join("\n");

  writeFile("config/language-mixes-all.js", banner);
}

function buildLanguageMapBundle() {
  const map = readJson("config/language-mixer-map.json");

  const banner = [
    '"use strict";',
    "",
    "// Auto-generated by tools/generate-language-mixer.js from config/language-mixer-map.json.",
    "// Edit the JSON source and rerun the generator if you change the mapping.",
    "(function(){",
    "  window.languageMixerMap = " + JSON.stringify(map, null, 2) + ";",
    "})();",
    ""
  ].join("\n");

  writeFile("config/language-mixer-map.js", banner);
}

function main() {
  buildLanguageMixesBundle();
  buildLanguageMapBundle();
}

if (require.main === module) main();
